// Writes packages/api/src/build-info.ts with the commit this build was made
// from, so the running service reports a build-derived SHA instead of a typed
// one. Railway exposes RAILWAY_GIT_COMMIT_SHA to the Docker build as a build
// argument (declared in the Dockerfile); CI has GITHUB_SHA; a local build asks git.
import fs from 'node:fs';
import { execSync } from 'node:child_process';

const fromEnv = [process.env.RAILWAY_GIT_COMMIT_SHA, process.env.GITHUB_SHA, process.env.SOURCE_COMMIT]
  .map((v) => String(v || '').trim())
  .find((v) => /^[0-9a-f]{7,40}$/i.test(v));
let sha = fromEnv || '';
let source = fromEnv ? 'build_env' : 'unknown';
if (!sha) {
  try {
    sha = execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
    if (/^[0-9a-f]{40}$/i.test(sha)) source = 'git';
    else sha = '';
  } catch {
    sha = '';
  }
}
const text = `// Generated by scripts/build-info.mjs at build time. Do not edit.
export const BUILD_COMMIT_SHA = ${JSON.stringify(sha || 'unknown')};
export const BUILD_COMMIT_SOURCE = ${JSON.stringify(source)} as 'build_env' | 'git' | 'unknown';
export const BUILD_TIME = ${JSON.stringify(new Date().toISOString())};
`;
fs.writeFileSync(new URL('../packages/api/src/build-info.ts', import.meta.url), text);
console.log(`build-info: ${sha || 'unknown'} (${source})`);
